// детерминированный выбор по дате: у каждого дня своя фраза, без повторов подряд
const dayNum = (ymd) => Math.floor(Date.parse(ymd + 'T12:00:00Z') / 864e5);
const pick = (arr, ymd, step) => arr[((dayNum(ymd) * step) % arr.length + arr.length) % arr.length];

export function quoteOf(ymd) { return pick(QUOTES, ymd, 7); }
export function tipOf(ymd, plan) {
  const has = (t) => plan && plan.items.some((i) => i.type === t);
  let pool = TIPS.general;
  if (has('control')) pool = TIPS.control;
  else if (plan && plan.items.some((i) => i.type === 'study' && i.tasks && i.tasks.some((t) => t.control))) pool = [...TIPS.control, ...TIPS.general];
  else if (has('gym') && dayNum(ymd) % 2) pool = TIPS.gym;
  else if (has('clean') && dayNum(ymd) % 2) pool = TIPS.clean;
  else if (plan && plan.items.some((i) => i.type === 'class' && i.end >= 1260)) pool = [...TIPS.late, ...TIPS.general];
  else if (plan && !plan.stats.classes && plan.dow <= 5) pool = [...TIPS.free, ...TIPS.general];
  return pick(pool, ymd, 5);
}
export function hanziOf(ymd, plan) {
  const has = (t) => plan && plan.items.some((i) => i.type === t);
  if (has('control')) return HANZI_THEME.control;
  if (has('gym') && dayNum(ymd) % 3 === 0) return HANZI_THEME.gym;
  if (has('clean') && dayNum(ymd) % 3 === 0) return HANZI_THEME.clean;
  return pick(HANZI, ymd, 11);
}
